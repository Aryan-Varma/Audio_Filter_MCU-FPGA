#!/usr/bin/env python3
"""
filter_designer.py
Designs, evaluates, and exports Q1.15 fixed-point FIR filter coefficients
for both MCU firmware (coefficients.h) and PC verification (coefficients_q15.txt).
All outputs are written directly to the current working directory.
"""

import argparse
from pathlib import Path
import numpy as np
import matplotlib.pyplot as plt
from scipy.signal import firwin, freqz


def design_and_quantize_fir(
    num_taps: int = 129,
    cutoff_hz: float = 4500.0,
    sample_rate: int = 48000,
    window: str = "hamming"
) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    """
    Synthesizes a low-pass FIR filter and quantizes coefficients to signed Q1.15.
    Returns (quantized_int16, float_taps, frequencies, freq_response_db).
    """
    # Generate ideal windowed floating-point coefficients
    h_float = firwin(num_taps, cutoff_hz, fs=sample_rate, window=window)

    # Q1.15 quantization: scale by 2^15, round to nearest integer, clip to int16 range
    # np.rint applies round half to even
    h_q15 = np.clip(np.rint(h_float * 32768.0), -32768, 32767).astype(np.int16)

    # Analyze frequency response of the actual quantized coefficients
    w_points = 32768
    f, h_resp = freqz(h_q15.astype(float) / 32768.0, worN=w_points, fs=sample_rate)
    h_db = 20.0 * np.log10(np.maximum(np.abs(h_resp), 1e-15))

    return h_q15, h_float, f, h_db


def export_c_header(
    h_q15: np.ndarray,
    output_path: Path,
    sample_rate: int,
    cutoff_hz: float
) -> None:
    """Exports quantized coefficients as a portable C header file for the MCU."""
    num_taps = len(h_q15)
    lines = [
        "/* Auto-generated by filter_designer.py - Do not modify manually */",
        "#ifndef COEFFICIENTS_H",
        "#define COEFFICIENTS_H",
        "",
        "#include <stdint.h>",
        "",
        f"#define FILTER_NUM_TAPS     ({num_taps})",
        f"#define FILTER_SAMPLE_RATE  ({sample_rate})",
        f"#define FILTER_CUTOFF_HZ    ({int(cutoff_hz)})",
        "",
        "/* Coefficients scaled in signed Q1.15 format [-32768, 32767] */",
        f"static const int16_t FILTER_TAPS[FILTER_NUM_TAPS] = {{"
    ]

    # Format numbers in clean rows of 8
    row = []
    for i, tap in enumerate(h_q15):
        row.append(f"{tap:6d}")
        if (i + 1) % 8 == 0 or (i + 1) == num_taps:
            lines.append("    " + ", ".join(row) + ("," if (i + 1) < num_taps else ""))
            row = []

    lines.extend([
        "};",
        "",
        "#endif /* COEFFICIENTS_H */",
        ""
    ])

    output_path.write_text("\n".join(lines))
    print(f"[+] Exported C header:     {output_path.name}")


def export_text_coefficients(h_q15: np.ndarray, output_path: Path) -> None:
    """Exports coefficients in plain integer text format for the Python testbench."""
    np.savetxt(output_path, h_q15, fmt="%d")
    print(f"[+] Exported text file:    {output_path.name}")


def plot_frequency_response(
    f: np.ndarray,
    h_db: np.ndarray,
    output_path: Path,
    sample_rate: int,
    cutoff_hz: float
) -> None:
    """Plots and saves the quantized filter's magnitude response."""
    fig, ax = plt.subplots(figsize=(8, 4.5))
    ax.plot(f, h_db, color="navy", lw=1.5, label="Quantized Q1.15 FIR")
    ax.axvline(cutoff_hz, color="crimson", linestyle="--", label=f"Cutoff ({cutoff_hz:.0f} Hz)")
    ax.axhline(-3.0, color="gray", linestyle=":", alpha=0.7)
    
    # Mark target bands
    passband_edge = 3000 if sample_rate == 48000 else 3000
    stopband_edge = 6000 if sample_rate == 48000 else 5000
    ax.axvline(passband_edge, color="darkgreen", linestyle=":", label=f"Passband Edge ({passband_edge} Hz)")
    ax.axvline(stopband_edge, color="darkorange", linestyle=":", label=f"Stopband Edge ({stopband_edge} Hz)")

    ax.set_title(f"Quantized Filter Frequency Response (N={len(f)*2 if False else 'Taps'}, Fs={sample_rate} Hz)")
    ax.set_xlabel("Frequency (Hz)")
    ax.set_ylabel("Magnitude (dB)")
    ax.set_xlim(0, sample_rate / 2)
    ax.set_ylim(-90, 5)
    ax.grid(True, linestyle="--", alpha=0.6)
    ax.legend(loc="upper right")
    fig.tight_layout()
    fig.savefig(output_path, dpi=180)
    plt.close(fig)
    print(f"[+] Saved response plot:   {output_path.name}")


def main() -> None:
    parser = argparse.ArgumentParser(description="Design and quantize Q1.15 FIR filter")
    parser.add_argument("--taps", type=int, default=129, help="Filter tap length (must be odd for integer delay)")
    parser.add_argument("--cutoff", type=float, default=4500.0, help="Cutoff frequency in Hz")
    parser.add_argument("--rate", type=int, default=48000, help="Sampling frequency in Hz")
    parser.add_argument("--window", type=str, default="hamming", help="Window type (hamming, hann, blackman)")
    parser.add_argument("--plot", action="store_true", help="Generate and save response plot")

    args = parser.parse_args()

    # Warn if tap count is even (would create fractional sample delay)
    if args.taps % 2 == 0:
        print("[!] Warning: Even tap count creates half-sample delay. Using odd count is recommended.")

    h_q15, _, f, h_db = design_and_quantize_fir(
        num_taps=args.taps,
        cutoff_hz=args.cutoff,
        sample_rate=args.rate,
        window=args.window
    )

    # Calculate metrics
    passband_mask = f <= (3000.0 if args.rate == 48000 else 3000.0)
    stopband_mask = f >= (6000.0 if args.rate == 48000 else 5000.0)

    pass_min = h_db[passband_mask].min()
    pass_max = h_db[passband_mask].max()
    stop_max = h_db[stopband_mask].max()

    print(f"[*] Filter Configuration: {args.taps} taps, Cutoff = {args.cutoff} Hz, Fs = {args.rate} Hz")
    print(f"[*] Group Delay:          {(args.taps - 1) // 2} samples ({(args.taps - 1) / (2 * args.rate) * 1000:.3f} ms)")
    print(f"[*] Passband Gain (<=3k): [{pass_min:.2f} dB, {pass_max:.2f} dB]")
    print(f"[*] Worst Stopband Gain:  {stop_max:.2f} dB")

    # Save to current working directory
    base_dir = Path(".")
    export_text_coefficients(h_q15, base_dir / "coefficients_q15.txt")
    export_c_header(h_q15, base_dir / "coefficients.h", args.rate, args.cutoff)

    if args.plot:
        plot_frequency_response(f, h_db, base_dir / "filter_response.png", args.rate, args.cutoff)


if __name__ == "__main__":
    main()