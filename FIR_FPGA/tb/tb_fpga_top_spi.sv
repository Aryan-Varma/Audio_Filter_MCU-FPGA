`timescale 1ns / 1ps

module tb_fpga_top_spi;

    // --- Clocks and Timing ---
    reg clk;          // 100 MHz FPGA system clock (10 ns period)
    reg rst_n;
    reg spi_sclk;     // SPI clock generated by master (e.g. 10 MHz -> 100 ns period)
    reg spi_cs_n;
    reg spi_mosi;
    wire spi_miso;
    wire fpga_ready_irq;

    // 100 MHz system clock
    always #5 clk = ~clk;

    // -------------------------------------------------------------
    // Device Under Test (DUT)
    // -------------------------------------------------------------
    fpga_fir_top #(
        .DATA_WIDTH(16),
        .MAX_TAPS(2048),
        .ADDR_WIDTH(11),
        .ACCUM_WIDTH(40),
        .DEFAULT_TAPS(129)
    ) dut (
        .clk(clk),
        .rst_n(rst_n),
        .spi_sclk(spi_sclk),
        .spi_cs_n(spi_cs_n),
        .spi_mosi(spi_mosi),
        .spi_miso(spi_miso),
        .fpga_ready_irq(fpga_ready_irq)
    );

    // Protocol Constants
    localparam [7:0] MAGIC_BYTE       = 8'hA5;
    localparam [7:0] CMD_STATUS       = 8'h01;
    localparam [7:0] CMD_WRITE_COEFF  = 8'h02;
    localparam [7:0] CMD_COMMIT       = 8'h03;
    localparam [7:0] CMD_SUBMIT       = 8'h04;
    localparam [7:0] CMD_READ_RESULT  = 8'h05;
    localparam [7:0] CMD_RESET_STREAM = 8'h06;

    // Test Memories
    reg [15:0] coeff_file_mem [0:128];
    reg [15:0] input_audio_mem [0:127]; // 64 frames = 128 samples
    reg [15:0] gold_audio_mem  [0:127];
    reg [7:0]  received_bytes  [0:255]; // 256 bytes returned

    // -------------------------------------------------------------
    // Master SPI Byte Transfer Task (Mode 0: sample rise, shift fall)
    // -------------------------------------------------------------
    task spi_transfer_byte(
        input  [7:0] byte_out,
        output [7:0] byte_in
    );
        integer bit_idx;
        begin
            byte_in = 8'h00;
            for (bit_idx = 7; bit_idx >= 0; bit_idx = bit_idx - 1) begin
                spi_mosi = byte_out[bit_idx];
                #50; // SCLK low time (50 ns)
                spi_sclk = 1'b1;
                byte_in[bit_idx] = spi_miso; // Sample on rising edge
                #50; // SCLK high time (50 ns)
                spi_sclk = 1'b0;
            end
        end
    endtask

    // -------------------------------------------------------------
    // Task: Send Complete SPI Packet
    // -------------------------------------------------------------
    task send_packet(
        input [7:0]  opcode,
        input [7:0]  epoch,
        input [7:0]  seq,
        input [15:0] length,
        input [7:0]  payload []
    );
        integer i;
        reg [7:0] dummy_rx;
        reg [7:0] chksum;
        begin
            chksum = MAGIC_BYTE ^ opcode ^ epoch ^ seq ^ length[15:8] ^ length[7:0];

            spi_cs_n = 1'b0; // Assert CS
            #100;

            // Header transmission
            spi_transfer_byte(MAGIC_BYTE, dummy_rx);
            spi_transfer_byte(opcode,     dummy_rx);
            spi_transfer_byte(epoch,      dummy_rx);
            spi_transfer_byte(seq,        dummy_rx);
            spi_transfer_byte(length[15:8], dummy_rx);
            spi_transfer_byte(length[7:0],  dummy_rx);

            // Payload transmission
            for (i = 0; i < length; i = i + 1) begin
                chksum = chksum ^ payload[i];
                spi_transfer_byte(payload[i], dummy_rx);
            end

            // Checksum transmission
            spi_transfer_byte(chksum, dummy_rx);

            #100;
            spi_cs_n = 1'b1; // De-assert CS
            #200;
        end
    endtask

    // -------------------------------------------------------------
    // Task: Read 256-Byte Audio Result
    // -------------------------------------------------------------
    task read_result_packet(
        input [7:0] epoch,
        input [7:0] seq
    );
        integer i;
        reg [7:0] dummy_rx;
        begin
            spi_cs_n = 1'b0;
            #100;

            // Send READ_RESULT header (Length = 256 bytes)
            spi_transfer_byte(MAGIC_BYTE, dummy_rx);
            spi_transfer_byte(CMD_READ_RESULT, dummy_rx);
            spi_transfer_byte(epoch, dummy_rx);
            spi_transfer_byte(seq, dummy_rx);
            spi_transfer_byte(8'd1, dummy_rx);   // Length MSB (256 = 0x0100)
            spi_transfer_byte(8'd0, dummy_rx);   // Length LSB

            // Stream 256 bytes back from MISO
            for (i = 0; i < 256; i = i + 1) begin
                spi_transfer_byte(8'h00, received_bytes[i]);
            end

            #100;
            spi_cs_n = 1'b1;
            #200;
        end
    endtask

    // -------------------------------------------------------------
    // Main Test Sequence
    // -------------------------------------------------------------
    reg [7:0] coeff_payload [0:257];
    reg [7:0] audio_payload [0:255];
    reg [7:0] empty_payload [0:0];
    integer k, mismatch_count;
    reg [15:0] recovered_sample;

    initial begin
        clk      = 0;
        rst_n    = 0;
        spi_sclk = 0;
        spi_cs_n = 1;
        spi_mosi = 0;

        // Reset Pulse
        repeat (10) @(posedge clk);
        rst_n = 1;
        repeat (10) @(posedge clk);

        $display("\n==================================================");
        $display("   STARTING END-TO-END SPI TOP-LEVEL TEST        ");
        $display("==================================================");

        // Step 1: Send RESET_STREAM command
        $display("[INFO] Step 1: Issuing RESET_STREAM...");
        send_packet(CMD_RESET_STREAM, 8'd1, 8'd0, 16'd0, empty_payload);
        #25000; // Wait 25 us for history RAM clearing counter to finish

        // Step 2: Load 129 Coefficients via WRITE_COEFF
        $display("[INFO] Step 2: Writing 129 coefficients into inactive bank...");
        $readmemh("tools/coefficients_q15.hex", coeff_file_mem);
        for (k = 0; k < 129; k = k + 1) begin
            coeff_payload[2*k]     = coeff_file_mem[k][7:0];  // Little-Endian Low
            coeff_payload[2*k + 1] = coeff_file_mem[k][15:8]; // High
        end
        send_packet(CMD_WRITE_COEFF, 8'd1, 8'd1, 16'd258, coeff_payload);

        // Step 3: Atomic COMMIT to switch active bank
        $display("[INFO] Step 3: Issuing COMMIT...");
        send_packet(CMD_COMMIT, 8'd1, 8'd2, 16'd0, empty_payload);

        // Step 4: Submit 64-Frame Audio Block (128 samples = 256 bytes)
        $display("[INFO] Step 4: Submitting Block 0 of Two-Tone Audio...");
        $readmemh("data/vectors/test_twotone_in.hex", input_audio_mem);
        $readmemh("data/vectors/test_twotone_expected.hex", gold_audio_mem);

        for (k = 0; k < 128; k = k + 1) begin
            audio_payload[2*k]     = input_audio_mem[k][7:0];
            audio_payload[2*k + 1] = input_audio_mem[k][15:8];
        end
        send_packet(CMD_SUBMIT, 8'd1, 8'd3, 16'd256, audio_payload);

        // Wait for DSP core to process (128 samples * 129 taps @ 100 MHz ~ 165 us)
        $display("[INFO] Waiting for FPGA filtering calculation to complete...");
        #200000; // Wait 200 us

        // Step 5: Read back filtered result via READ_RESULT
        $display("[INFO] Step 5: Reading filtered result over SPI...");
        read_result_packet(8'd1, 8'd3);

        // Step 6: Verify output sample-by-sample
        mismatch_count = 0;
        for (k = 0; k < 128; k = k + 1) begin
            recovered_sample = {received_bytes[2*k + 1], received_bytes[2*k]};
            if ($signed(recovered_sample) !== $signed(gold_audio_mem[k])) begin
                $display("[ERROR] Sample %0d Mismatch! Got: %0d, Expected: %0d",
                         k, $signed(recovered_sample), $signed(gold_audio_mem[k]));
                mismatch_count = mismatch_count + 1;
            end
        end

        if (mismatch_count == 0) begin
            $display("[PASS] SPI Audio Block 0 verified: All 128 samples match golden reference!\n");
        end else begin
            $display("[FAIL] SPI Audio Block 0 completed with %0d errors!\n", mismatch_count);
        end

        // Step 7: Corner-Case Test - Aborted SPI Transaction
        $display("[INFO] Step 7: Testing aborted transaction robustness...");
        spi_cs_n = 1'b0;
        #100;
        spi_transfer_byte(MAGIC_BYTE, received_bytes[0]);
        spi_transfer_byte(CMD_SUBMIT, received_bytes[0]);
        #50;
        spi_cs_n = 1'b1; // Abort packet early!
        #200;

        // Verify chip didn't freeze and accepts next packet
        send_packet(CMD_STATUS, 8'd1, 8'd4, 16'd0, empty_payload);
        $display("[PASS] SPI Parser recovered cleanly from aborted packet!\n");

        $display("==================================================");
        $display("   ALL TOP-LEVEL SPI TESTS PASSED SUCCESSFULLY!   ");
        $display("==================================================");
        $stop;
    end

endmodule